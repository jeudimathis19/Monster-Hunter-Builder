export const LANGS = ['fr', 'en'];
let current = prefs.get('lang', null) || ((navigator.language || 'fr').toLowerCase().startsWith('fr') ? 'fr' : 'en');
if (!LANGS.includes(current)) current = 'fr';

export const getLang = () => current;
export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : 'fr';
  prefs.set('lang', current);
  document.documentElement.lang = current;
}

/** Translates a key, replacing {placeholders}. Falls back to French then to the key. */
export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.fr[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}

